import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { PDFDocument } from 'pdf-lib';
import { createRenames } from '../src/features/rename.js';

const output = '.impeccable/review/features';
await mkdir(output, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await page.addInitScript(() => { localStorage.setItem('imageinplace-welcome-dismissed', 'true'); localStorage.setItem('imageinplace-locale', 'es'); });
await page.goto(process.env.TEST_URL || 'http://127.0.0.1:4180');
const fixture = (name, width, height) => ({ name, mimeType: 'image/svg+xml', buffer: Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><rect width="100%" height="100%" fill="#008800"/></svg>`) });
await page.locator('input[type=file]').setInputFiles([fixture('clase.svg', 600, 400), fixture('vertical.svg', 400, 600)]);
const cards = page.locator('.image-card-select');
await cards.first().waitFor();
assert.equal(await cards.count(), 2, 'Import must not duplicate the first file');
const initialUrls = await page.locator('.image-thumb img').evaluateAll((images) => images.map((image) => image.src));
const action = async (name) => {
  const button = page.getByRole('button', { name, exact: true });
  if (!(await button.isVisible())) await page.getByRole('button', { name: 'Más acciones', exact: true }).click();
  await button.click();
};
const sidebar = page.locator('.gallery-side-panel');
await action('Márgenes y lienzo');
await sidebar.getByLabel('Ancho del lienzo (px)', { exact: true }).fill('400');
await sidebar.getByLabel('Alto del lienzo (px)', { exact: true }).fill('400');
await sidebar.getByLabel('Relleno alrededor (px)', { exact: true }).fill('20');
await action('Crear lienzo');
await page.waitForFunction(() => !document.querySelector('.canvas-panel'));
await page.waitForFunction(() => [...document.querySelectorAll('.image-thumb img')].every((image) => image.complete && image.naturalWidth === 400 && image.naturalHeight === 400));
const pixels = await page.locator('.image-thumb img').first().evaluate((image) => {
  const canvas = document.createElement('canvas'); canvas.width = 400; canvas.height = 400;
  const context = canvas.getContext('2d'); context.drawImage(image, 0, 0);
  return [Array.from(context.getImageData(0, 0, 1, 1).data), Array.from(context.getImageData(200, 200, 1, 1).data), Array.from(context.getImageData(200, 65, 1, 1).data)];
});
assert.deepEqual(pixels, [[255,255,255,255],[0,136,0,255],[255,255,255,255]], 'Canvas must fit without stretching');
await action('Deshacer global');
assert.deepEqual(await page.locator('.image-thumb img').evaluateAll((images) => images.map((image) => image.src)), initialUrls);
await action('Rehacer global');
await action('Renombrar selección');
await sidebar.getByLabel('Patrón', { exact: true }).fill('Ficha-{n}');
await action('Aplicar nombres');
assert.match(await cards.first().innerText(), /Ficha-01.png/);
await action('Restaurar originales seleccionados');
assert.match(await cards.first().innerText(), /clase.svg/);
await action('Comprimir a un peso objetivo');
await sidebar.getByLabel('Tamaño máximo por imagen (KB)').fill('20');
await action('Comprimir selección');
await page.getByRole('button', { name: 'Aplicar resultados', exact: true }).waitFor();
assert.equal(await sidebar.locator('.compression-ok').count(), 2);
await action('Aplicar resultados');
await sidebar.getByRole('button', { name: 'Cerrar', exact: true }).click();
await action('Cerrar todas las imágenes');
assert.equal(await cards.count(), 0);
await action('Deshacer global');
assert.equal(await cards.count(), 2, 'Undo deletion must restore images');
await page.locator('.image-card-edit').first().click();
await page.getByRole('button', { name: 'Anotar', exact: true }).click();
await page.getByRole('button', { name: 'Texto', exact: true }).click();
await page.getByLabel('Texto / número', { exact: true }).fill('Lección 1');
await page.screenshot({ path: `${output}/annotations.png` });
await page.getByRole('button', { name: 'Guardar cambios', exact: true }).click();
await page.waitForFunction(() => !document.querySelector('.individual-editor'));
// Select both restored images explicitly after testing deletion undo.
for (let index = 0; index < await cards.count(); index++) {
  if (await cards.nth(index).getAttribute('aria-pressed') !== 'true') await cards.nth(index).click();
}
await action('Crear láminas A4');
await sidebar.getByLabel('Filas', { exact: true }).fill('1');
await sidebar.getByLabel('Columnas', { exact: true }).fill('1');
await sidebar.getByLabel('Margen (mm)', { exact: true }).fill('0');
await sidebar.getByLabel('Título opcional', { exact: true }).fill('Fichas 日本語 😀');
const downloadPromise = page.waitForEvent('download');
await action('Descargar PDF');
const download = await downloadPromise;
await download.saveAs(`${output}/sheets.pdf`);
const pdf = await PDFDocument.load(await readFile(`${output}/sheets.pdf`));
assert.equal(pdf.getPageCount(), 2);
assert.ok(Math.abs(pdf.getPage(0).getWidth() - 595.2756) < 0.01);
assert.ok(Math.abs(pdf.getPage(0).getHeight() - 841.8898) < 0.01);
await page.screenshot({ path: `${output}/sheets.png` });
await sidebar.getByRole('button', {name:'Cerrar', exact:true}).click();
await action('Flujos reutilizables');
await sidebar.getByRole('button', {name:'Añadir paso', exact:true}).click();
await sidebar.getByLabel('Máximo (px)', {exact:true}).fill('200');
await sidebar.getByLabel('Tipo de paso', {exact:true}).selectOption('format');
await sidebar.getByRole('button', {name:'Añadir paso', exact:true}).click();
await sidebar.locator('.workflow-step').last().locator('select').selectOption('png');
await sidebar.getByLabel('Tipo de paso', {exact:true}).selectOption('rename');
await sidebar.getByRole('button', {name:'Añadir paso', exact:true}).click();
await sidebar.getByLabel('Patrón', {exact:true}).fill('Ficha-{n}');
await sidebar.getByPlaceholder('Nombre del flujo').fill('Aula compacta');
await sidebar.getByRole('button', {name:'Guardar', exact:true}).click();
await action('Aplicar flujo');
await page.waitForFunction(() => [...document.querySelectorAll('.image-thumb img')].every((image) => image.complete && Math.max(image.naturalWidth, image.naturalHeight) === 200));
assert.deepEqual(await page.locator('.image-card-meta strong').allTextContents(), ['Ficha-01.png', 'Ficha-02.png']);
await page.reload();
await page.locator('input[type=file]').setInputFiles([fixture('nueva.svg', 600, 400)]);
await action('Flujos reutilizables');
await sidebar.locator('.workflow-saved select').selectOption('Aula compacta');
assert.equal(await sidebar.getByLabel('Máximo (px)', {exact:true}).inputValue(), '200');
await action('Aplicar flujo');
await page.waitForFunction(() => document.querySelector('.image-thumb img')?.naturalWidth === 200);
assert.equal(errors.length, 0, errors.join('\n'));
await page.screenshot({ path: `${output}/gallery.png` });
await browser.close();
assert.equal(createRenames([{id:'1', name:'old.svg', type:'image/png'}], {pattern:'CON'})[0].name, '_CON.png');
console.log('Feature checks passed: import, canvas pixels, history, rename, compression, annotations, multipage Unicode A4 PDF, persisted workflows.');
